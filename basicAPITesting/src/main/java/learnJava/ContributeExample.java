public class ContributeExample {
         public static void main(String[] args) {
            int a = 4;
            int b = 5;
            int result = a++ + --b + b++ + ++a - a;
            System.out.println("a: " + a);
            System.out.println("b: " + b);
            System.out.println("result: " + result);
        }
    }




